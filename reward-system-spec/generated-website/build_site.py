# --- Math protection ------------------------------------------------------

_MATH_PLACEHOLDER = "@@MATH{idx}@@"


def protect_math(text: str) -> tuple[str, list[str]]:
    """Replace $...$ and $$...$$ spans with placeholders to keep markdown
    from interpreting underscores, asterisks, etc. inside them. Also
    disambiguate currency $ (e.g. ``$6,500``) from inline math delimiters.

    Strategy:
        1. Protect ``$$...$$`` display math (most specific).
        2. Protect inline math ``$...$`` whose content contains a LaTeX
           command (``\\pi``, ``\\frac``, etc.) — strong math signal.
        3. Protect *very short* inline math spans (1–4 non-space chars)
           like ``$i$``, ``$x+y$``, ``$0.5$``. These are unambiguous math.
        4. Escape any remaining ``$`` that is immediately followed by a
           digit as HTML-encoded ``\\$`` (``&#92;$``), so MathJax
           ``processEscapes:true`` ignores it. This prevents two currency
           ``$`` in the same paragraph from being paired as math.

    Returns (text_with_placeholders, list_of_original_spans).
    """
    spans: list[str] = []

    def _store(match: re.Match) -> str:
        idx = len(spans)
        spans.append(match.group(0))
        return _MATH_PLACEHOLDER.format(idx=idx)

    # 1. Display math
    text = re.sub(r"\$\$([\s\S]+?)\$\$", _store, text)
    # 2. Inline math whose body contains a LaTeX control sequence (backslash).
    text = re.sub(r"(?<!\\)\$([^\$\n]*\\[^\$\n]*)\$", _store, text)
    # 3. Short inline math with no whitespace — $i$, $x+y$, $1/2$, $0.5$.
    text = re.sub(r"(?<!\\)\$([^\$\n\s]{1,4})\$", _store, text)
    # 4. Remaining $<digit> is prose currency — escape so MathJax skips it.
    text = re.sub(r"(?<!\\)\$(?=\d)", r"&#92;$", text)
    return text, spans


def restore_math(html: str, spans: list[str]) -> str:
    for idx, span in enumerate(spans):
        html = html.replace(_MATH_PLACEHOLDER.format(idx=idx), span)
    return html


# --- Link & image rewriting -----------------------------------------------


def _resolve_rel(src_md: Path, target: str) -> Path:
    return (src_md.parent / target).resolve()


def _rel_to_site(src_md: Path, target: str) -> str:
    """Compute a path suitable for the HTML output (relative to SITE_DIR),
    given a relative path written in the MD.

    Convention: if the resolved path lies under diagnostic/, the leading
    "diagnostic/" is stripped, because figures are mirrored into
    generated-website/ without that prefix.
    """
    target_abs = _resolve_rel(src_md, target)
    try:
        rel = target_abs.relative_to(REPO_ROOT)
    except ValueError:
        # Outside repo root — return as-is
        return target
    rel_str = rel.as_posix()
    if rel_str.startswith("diagnostic/"):
        rel_str = rel_str[len("diagnostic/"):]
    return rel_str


def rewrite_md_link(link: str, src_md: Path) -> str:
    """Rewrite a MD-source link for the HTML output."""
    if not link or link.startswith(("#", "http://", "https://", "mailto:", "tel:", "ftp://")):
        return link
    # Split out anchor
    anchor = ""
    if "#" in link:
        link, anchor = link.split("#", 1)
        anchor = "#" + anchor
    # .md links → map to .html
    if link.endswith(".md"):
        target_abs = _resolve_rel(src_md, link)
        try:
            rel = target_abs.relative_to(REPO_ROOT).as_posix()
        except ValueError:
            return link + anchor
        if rel in MD_TO_HTML_MAP:
            return MD_TO_HTML_MAP[rel] + anchor
        # Unknown MD: keep but warn
        print(f"  warn: unmapped MD link → {rel}", file=sys.stderr)
        return link + anchor
    # Other relative paths (figures, directories): rewrite to site-relative
    return _rel_to_site(src_md, link) + anchor


_TOC_BLOCK_RE = re.compile(
    r"(^#{1,2}\s+Table of Contents\s*\n)([\s\S]*?)(?=^#{1,6}\s|^---\s*$|\Z)",
    re.MULTILINE,
)


_LIST_ITEM_RE = re.compile(r"^(\d+\.|[-*+])\s")


def _normalize_toc_indent(block: str) -> str:
    """Re-indent a TOC block so each nesting level is exactly 4 spaces.

    The source MDs use ad-hoc indentation: 3 spaces for the first sub-level,
    5–6 spaces for the second, 7–9 for the third, etc. python-markdown's
    ``sane_lists`` requires strict 4-space indentation per level, otherwise
    nested lines are folded into the parent item as text.

    This walks the block line-by-line, tracks observed indents on a stack,
    and emits ``level * 4`` spaces in front of each list-item line.
    """
    lines = block.splitlines(keepends=True)
    indents: list[int] = []  # ascending stack of indent widths observed
    out: list[str] = []
    for line in lines:
        stripped = line.lstrip(" ")
        if not stripped.strip():
            out.append(line)
            continue
        if not _LIST_ITEM_RE.match(stripped):
            # Not a list marker — keep original indent
            out.append(line)
            continue
        indent = len(line) - len(stripped)
        # Pop deeper levels that no longer apply
        while indents and indent < indents[-1]:
            indents.pop()
        if not indents or indent > indents[-1]:
            indents.append(indent)
        level = len(indents) - 1
        out.append(" " * (level * 4) + stripped)
    return "".join(out)


def normalize_toc_indentation(md_text: str) -> str:
    """Find the Table of Contents block and normalize its indentation."""
    def _sub(m: re.Match) -> str:
        return m.group(1) + _normalize_toc_indent(m.group(2))

    return _TOC_BLOCK_RE.sub(_sub, md_text, count=1)


def preprocess_md(md_text: str, src_md: Path) -> str:
    """Rewrite MD links/images before feeding to the markdown parser.

    Using the MD source representation keeps python-markdown's TOC slugifier
    working the same way as the rest of the page (we don't need to touch the
    rendered HTML for anchors). We only rewrite the path part of ``[..](..)``
    and ``![..](..)`` constructs.
    """
    md_text = normalize_toc_indentation(md_text)
    # Images: ![alt](path)  — the path may include a title "title"
    img_re = re.compile(r"(!\[[^\]]*\]\()([^)\s]+)(\s+\"[^\"]*\")?(\))")

    def _img_sub(m: re.Match) -> str:
        prefix, path, title, suffix = m.group(1), m.group(2), m.group(3) or "", m.group(4)
        # External or anchor-only: keep
        if path.startswith(("http://", "https://", "data:", "/", "#")):
            return m.group(0)
        new_path = _rel_to_site(src_md, path)
        return f"{prefix}{new_path}{title}{suffix}"

    md_text = img_re.sub(_img_sub, md_text)

    # Links: [text](path)  — but not images (which are ![...])
    link_re = re.compile(r"(?<!\!)(\[(?:[^\[\]]|\[[^\]]*\])*\]\()([^)\s]+)(\s+\"[^\"]*\")?(\))")

    def _link_sub(m: re.Match) -> str:
        prefix, path, title, suffix = m.group(1), m.group(2), m.group(3) or "", m.group(4)
        new_path = rewrite_md_link(path, src_md)
        return f"{prefix}{new_path}{title}{suffix}"

    md_text = link_re.sub(_link_sub, md_text)
    return md_text


# --- Section-reference auto-decoration ------------------------------------

# After conversion, bare "§X.X.X" link texts are expanded to "§X.X.X — Title"
# using the heading map of the target page. The index is built once per build
# from the PAGES MD sources, using python-markdown's own TOC slugifier so the
# anchors match the rendered HTML without any guessing.

_TITLE_INDEX: dict[str, dict[str, str]] = {}  # html_name → {slug: display_title}

_SECNUM_PREFIX_RE = re.compile(r"^\d+(?:\.\d+)*\.?\s+")


def _strip_section_number(title: str) -> str:
    """Remove leading section numbers like '1.2.4.2 ' or '1.3. ' from a heading display."""
    return _SECNUM_PREFIX_RE.sub("", title).strip()


def _walk_toc_tokens(tokens: list, out: dict[str, str]) -> None:
    for t in tokens:
        out[t["id"]] = _strip_section_number(t["name"])
        _walk_toc_tokens(t.get("children", []), out)


def build_title_index() -> None:
    """Populate _TITLE_INDEX with a slug→title map for each output page.

    Runs python-markdown in TOC-only mode on each MD source. The resulting
    tokens expose ``id`` (slug) and ``name`` (visible heading text); those are
    the exact anchors that the real conversion produces, so no reinvention of
    slugification rules is needed.
    """
    _TITLE_INDEX.clear()
    for page in PAGES:
        src_md = REPO_ROOT / page["md"]
        if not src_md.exists():
            continue
        md_text = src_md.read_text()
        md_text, _ = protect_math(md_text)
        md = markdown.Markdown(
            extensions=["toc"],
            extension_configs={"toc": {"permalink": False, "anchorlink": False}},
        )
        md.convert(md_text)
        title_map: dict[str, str] = {}
        _walk_toc_tokens(getattr(md, "toc_tokens", []), title_map)
        _TITLE_INDEX[page["html"]] = title_map


_HREF_RE = re.compile(r'href="([^"]*)"', re.IGNORECASE)
_SECNUM_LINK_RE = re.compile(
    r"<a(\s+[^>]*?)>\s*§\s*(\d+(?:\.\d+)+)\s*</a>",
    re.IGNORECASE,
)

# Cap long titles in the decoration so they don't blow up line length.
_TITLE_MAX_LEN = 80


def decorate_section_references(html_body: str, this_page_html: str) -> str:
    """Rewrite ``<a href="...">§X.X</a>`` → ``<a ...>§X.X — Title</a>``.

    Only link texts that are *exactly* a section number are touched, so any
    manually-written decoration like ``[*The Intended Game* §1.3.2](...)`` is
    left alone. If the anchor is unknown (cross-file to an unmapped .md, a
    missing target, a fragment that doesn't exist), the link is kept as-is.
    """

    def _sub(m: re.Match) -> str:
        attrs = m.group(1)
        secnum = m.group(2)
        href_m = _HREF_RE.search(attrs)
        if not href_m:
            return m.group(0)
        href = href_m.group(1)
        if "#" in href:
            path, _, fragment = href.partition("#")
        else:
            path, fragment = href, ""
        if not fragment:
            return m.group(0)
        target_html = path or this_page_html
        titles = _TITLE_INDEX.get(target_html)
        if titles is None:
            return m.group(0)
        title = titles.get(fragment)
        if not title:
            return m.group(0)
        # TOC tokens may already contain HTML entities (e.g. "&amp;" for "&").
        # Unescape first so we don't double-escape when we re-encode below.
        title = _html.unescape(title)
        if len(title) > _TITLE_MAX_LEN:
            title = title[: _TITLE_MAX_LEN - 1].rstrip() + "…"
        new_text = f"§{secnum} — {_html.escape(title)}"
        return f"<a{attrs}>{new_text}</a>"

    return _SECNUM_LINK_RE.sub(_sub, html_body)


# --- Markdown → HTML ------------------------------------------------------


def md_to_html(md_text: str) -> str:
    """Convert Markdown to HTML with our extension set.

    Math is protected around the conversion so $...$ contents pass through
    verbatim for MathJax.
    """
    md_text, math_spans = protect_math(md_text)

    md = markdown.Markdown(
        extensions=[
            "tables",
            "fenced_code",
            "attr_list",
            "sane_lists",
            "footnotes",
            "md_in_html",
            "toc",
        ],
        extension_configs={
            "toc": {"permalink": False, "anchorlink": False},
        },
        output_format="html5",
    )
    html_out = md.convert(md_text)
    html_out = restore_math(html_out, math_spans)
    html_out = _mermaidize(html_out)
    return html_out


# --- Mermaid: promote fenced ``` mermaid ``` to <div class="mermaid"> -----

_MERMAID_RE = re.compile(
    r'<pre><code class="(?:language-)?mermaid">([\s\S]*?)</code></pre>',
    re.IGNORECASE,
)


def _mermaidize(html_out: str) -> str:
    """Replace Mermaid code fences with divs so the client-side mermaid.js
    library can render them as SVG. The code content is HTML-unescaped so the
    original Mermaid source (including ``<b>`` and ``<br/>`` in node labels)
    is handed to the renderer verbatim.
    """
    def _sub(m: "re.Match[str]") -> str:
        return f'<div class="mermaid">{_html.unescape(m.group(1))}</div>'
    return _MERMAID_RE.sub(_sub, html_out)


# --- TOC wrapping (promote manual TOC to <nav class="toc-nav">) -----------


_TOC_HEADING_RE = re.compile(
    r'<h[12][^>]*id="table-of-contents"[^>]*>Table of Contents</h[12]>',
    re.IGNORECASE,
)
_LIST_OPEN_RE = re.compile(r"<(?:ul|ol)\b[^>]*>", re.IGNORECASE)
_LIST_TAG_RE = re.compile(r"<(/?)(ul|ol)\b[^>]*>", re.IGNORECASE)


def _find_matching_list_end(html: str, start: int) -> int:
    """Starting at index ``start`` (pointing at ``<ul`` or ``<ol``), return the
    index just past the matching closing list tag, using depth counting so
    nested lists don't close the outer too early.

    Tracks both ``<ul>`` and ``<ol>`` together; returns -1 if no matching close.
    """
    depth = 0
    pos = start
    while pos < len(html):
        m = _LIST_TAG_RE.search(html, pos)
        if not m:
            return -1
        if m.group(1) == "":  # opening
            depth += 1
        else:  # closing
            depth -= 1
            if depth == 0:
                return m.end()
        pos = m.end()
    return -1


def wrap_manual_toc(html_body: str) -> str:
    heading = _TOC_HEADING_RE.search(html_body)
    if not heading:
        return html_body
    list_open = _LIST_OPEN_RE.search(html_body, heading.end())
    if not list_open:
        return html_body
    # Only accept a list that's immediately after the heading (whitespace-only gap)
    gap = html_body[heading.end():list_open.start()]
    if gap.strip():
        return html_body
    list_end = _find_matching_list_end(html_body, list_open.start())
    if list_end < 0:
        return html_body
    return (
        html_body[: heading.end()]
        + gap
        + "<nav class=\"toc-nav\">\n"
        + html_body[list_open.start() : list_end]
        + "\n</nav>"
        + html_body[list_end:]
    )


