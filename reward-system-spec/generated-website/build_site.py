def sync_references() -> None:
    """Mirror ``references/`` PDFs with their subfolder structure.

    The nav bar links to flat paths (``references/foo.pdf``) while source MDs
    reference subfolders (``references/research-papers/foo.pdf``). Both need
    to work: we keep the flat mirror already in place and additionally copy
    each PDF into its subfolder location.
    """
    src_root = REPO_ROOT / "references"
    dst_root = SITE_DIR / "references"
    if not src_root.exists():
        return
    copied = 0
    for sub in src_root.iterdir():
        if not sub.is_dir():
            continue
        dst_sub = dst_root / sub.name
        dst_sub.mkdir(parents=True, exist_ok=True)
        for f in sub.iterdir():
            if f.is_file() and f.suffix.lower() == ".pdf":
                target = dst_sub / f.name
                if (not target.exists()) or (f.stat().st_mtime > target.stat().st_mtime):
                    shutil.copy2(f, target)
                    copied += 1
    if copied:
        print(f"  synced {copied} reference PDFs (subfolder mirror)")


