_CSS_TAG = re.compile(r"<style>([\s\S]*?)</style>", re.IGNORECASE)
_JS_TAG = re.compile(r"<script>\s*\(function\(\)\{([\s\S]*?)\}\)\(\);\s*</script>", re.IGNORECASE)


def extract_shared_assets() -> None:
    """Extract the big inline CSS block and the bottom JS IIFE from the
    current index.html into assets/site.css and assets/site.js.

    This is a one-time migration: once the assets exist, the generated
    pages all share them via <link> / <script src>.
    """
    assets_dir = SITE_DIR / "assets"
    assets_dir.mkdir(exist_ok=True)
    css_path = assets_dir / "site.css"
    js_path = assets_dir / "site.js"
    if css_path.exists() and js_path.exists():
        ensure_floating_toc_assets()
        return

    idx_html = (SITE_DIR / "index.html").read_text()
    m = _CSS_TAG.search(idx_html)
    if m:
        css_path.write_text(m.group(1).strip() + "\n")
        print(f"  wrote {css_path.relative_to(SITE_DIR)}")
    m = _JS_TAG.search(idx_html)
    if m:
        js_path.write_text("(function(){\n" + m.group(1).strip() + "\n})();\n")
        print(f"  wrote {js_path.relative_to(SITE_DIR)}")
    ensure_floating_toc_assets()


